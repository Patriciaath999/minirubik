#!/usr/bin/env python3
"""Generate the RV32I data section for rubic.s.

Same definitions as solver.c (source/twist, Lehmer permutation rank, base-3
orientation rank over the first six corners) and the same layout as tables.h:
  perm_move[3][5040], orient_move[3][729]  quarter-turn transitions (u16)
  perm_dist[5040],    orient_dist[729]     pattern-database distances (u8)
Usage: gen_tables.py core.s > rubic.s
"""
import sys
from collections import deque
from itertools import permutations

SOURCE = [[1, 4, 2, 0, 3, 5, 6], [0, 1, 2, 4, 5, 6, 3], [0, 2, 5, 3, 1, 4, 6]]
TWIST = [[1, 2, 0, 2, 1, 0, 0], [0, 0, 0, 1, 2, 1, 2], [0, 0, 0, 0, 0, 0, 0]]


def rank_p(p):
    r = 0
    for i in range(7):
        r = r * (7 - i) + sum(1 for j in range(i + 1, 7) if p[j] < p[i])
    return r


def rank_o(o):
    r = 0
    for i in range(6):
        r = r * 3 + o[i]
    return r


def unrank_o(r):
    o = [0] * 7
    for i in range(5, -1, -1):
        o[i] = r % 3
        r //= 3
    o[6] = (3 - sum(o[:6]) % 3) % 3
    return o


perms = sorted(permutations(range(7)), key=rank_p)
assert all(rank_p(p) == i for i, p in enumerate(perms))

perm_move = [[rank_p([p[SOURCE[f][i]] for i in range(7)]) for p in perms]
             for f in range(3)]
orient_move = []
for f in range(3):
    row = []
    for r in range(729):
        o = unrank_o(r)
        row.append(rank_o([(o[SOURCE[f][i]] + TWIST[f][i]) % 3 for i in range(7)]))
    orient_move.append(row)


def bfs(move, n):
    dist = [255] * n
    dist[0] = 0
    q = deque([0])
    while q:
        x = q.popleft()
        for f in range(3):
            y = x
            for _ in range(3):          # X, X2, X'
                y = move[f][y]
                if dist[y] == 255:
                    dist[y] = dist[x] + 1
                    q.append(y)
    assert 255 not in dist
    return dist


perm_dist = bfs(perm_move, 5040)
orient_dist = bfs(orient_move, 729)


def emit(label, directive, values, per_line=16):
    out = [f"{label}:"]
    for i in range(0, len(values), per_line):
        out.append(f"    {directive} " + ",".join(map(str, values[i:i + per_line])))
    return "\n".join(out)


if __name__ == "__main__":
    sys.stdout.write(open(sys.argv[1]).read())
    print("\n    /* ---- generated by gen_tables.py: identical to tables.h ---- */")
    print("    .align 2")
    print(emit("perm_move", ".half", perm_move[0] + perm_move[1] + perm_move[2]))
    print(emit("orient_move", ".half", orient_move[0] + orient_move[1] + orient_move[2]))
    print(emit("perm_dist", ".byte", perm_dist))
    print(emit("orient_dist", ".byte", orient_dist))
    import geometry
    print("    .align 2")
    print("    /* ---- renderer tables (geometry.py, derived from source/twist) ---- */")
    print(geometry.render_tables())
